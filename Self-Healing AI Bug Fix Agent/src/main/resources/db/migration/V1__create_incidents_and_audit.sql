CREATE TABLE incidents (
    id UUID PRIMARY KEY,
    service_name VARCHAR(120) NOT NULL,
    repository_identifier VARCHAR(180) NOT NULL,
    branch_name VARCHAR(120) NOT NULL,
    error_message VARCHAR(4000) NOT NULL,
    sanitized_stack_trace TEXT NOT NULL,
    environment_name VARCHAR(80),
    correlation_id VARCHAR(120),
    idempotency_key VARCHAR(120),
    status VARCHAR(32) NOT NULL,
    stage VARCHAR(1000),
    diagnosis_json TEXT,
    evidence_json TEXT,
    result_json TEXT,
    changed_files_json TEXT,
    pull_request_url VARCHAR(1000),
    attempt_count INTEGER NOT NULL DEFAULT 0,
    escalation_reason VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_incidents_idempotency_key UNIQUE (idempotency_key)
);

CREATE INDEX idx_incidents_status_created ON incidents (status, created_at);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id UUID NOT NULL REFERENCES incidents (id),
    actor_type VARCHAR(40) NOT NULL,
    action VARCHAR(120) NOT NULL,
    summary VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_audit_events_incident_created ON audit_events (incident_id, created_at);

CREATE TABLE healing_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id UUID NOT NULL REFERENCES incidents (id),
    attempt_number INTEGER NOT NULL,
    patch_summary VARCHAR(1000),
    changed_files_json TEXT,
    command VARCHAR(1000),
    exit_code INTEGER,
    duration_millis BIGINT,
    output TEXT,
    timed_out BOOLEAN NOT NULL,
    sandboxed BOOLEAN NOT NULL,
    passed BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_attempts_incident_number UNIQUE (incident_id, attempt_number)
);

CREATE INDEX idx_attempts_incident_created ON healing_attempts (incident_id, created_at);